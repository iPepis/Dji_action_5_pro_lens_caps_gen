import * as THREE from 'three';
import { OrbitControls } from 'three/examples/jsm/controls/OrbitControls.js';
import Module from 'manifold-3d';
import opentype from 'opentype.js';
import wasmBytes from 'manifold-3d/manifold.wasm';
import fontBytes from 'fonts:all';   // Uint8Array[] of the bundled fonts, generated by scripts/build.mjs
import { buildCap, manifoldToArrays, toBinarySTL, missingChars, GRIPS, DENSITY, CAMERAS, SQUARE_GRIPS, capSize } from './core.js';

const $ = (id) => document.getElementById(id);
const el = {
  text: $('text'), textCount: $('textCount'), size: $('size'), sizeVal: $('sizeVal'),
  cam: $('cam'), fit: $('fit'), custom: $('custom'), customWrap: $('customWrap'),
  grip: $('grip'), count: $('count'), countVal: $('countVal'),
  exportBtn: $('exportBtn'), resetBtn: $('resetBtn'), status: $('status'), note: $('note'),
  stage: $('stage'), canvas: $('canvas'),
};

// ---------- three.js preview ----------
const renderer = new THREE.WebGLRenderer({ canvas: el.canvas, antialias: true, alpha: true });
renderer.setPixelRatio(Math.min(devicePixelRatio, 2));
const scene = new THREE.Scene();
const camera = new THREE.PerspectiveCamera(35, 1, 1, 400);
camera.up.set(0, 1, 0);   // we look at the top face from outside (from -Z), so +Y up keeps the text upright
const controls = new OrbitControls(camera, el.canvas);
controls.enableDamping = true;
controls.target.set(0, 0, 5);
scene.add(new THREE.HemisphereLight(0xffffff, 0x445066, 1.15));
const key = new THREE.DirectionalLight(0xffffff, 2.2); key.position.set(-30, -50, -60); scene.add(key);
const rim = new THREE.DirectionalLight(0x9fc2ff, 1.1); rim.position.set(50, 40, 30); scene.add(rim);
const mat = new THREE.MeshStandardMaterial({ color: 0xe9ecf2, roughness: 0.55, metalness: 0.05, flatShading: true });
let mesh = null;

function resetView() {
  // look at the top face (it faces -Z) from outside, slightly above
  camera.position.set(18, -36, -92);
  controls.target.set(0, 0, 4);
  controls.update();
}
function resize() {
  const r = el.stage.getBoundingClientRect();
  renderer.setSize(r.width, r.height, false);
  camera.aspect = r.width / r.height; camera.updateProjectionMatrix();
}
new ResizeObserver(resize).observe(el.stage);
resetView(); resize();
(function loop() { controls.update(); renderer.render(scene, camera); requestAnimationFrame(loop); })();
el.resetBtn.addEventListener('click', resetView);

// ---------- generator ----------
let wasm = null, bundled = [], current = null, timer = null, busy = false, dirty = false;

function params() {
  const fit = el.fit.value;
  const cam = CAMERAS.find((c) => c.id === el.cam.value) || CAMERAS[0];   // before a pick: preview only, export stays off
  const boreD = fit === 'custom' ? Math.min(Math.max(parseFloat(el.custom.value) || cam.bore, 15), 60) : +(cam.bore + parseFloat(fit)).toFixed(2);
  return {
    text: el.text.value, boreD, depth: cam.depth, shape: cam.shape, corner: cam.corner,
    grip: el.grip.value, gripCount: parseInt(el.count.value, 10),
    sizeFactor: parseInt(el.size.value, 10) / 100,
  };
}

function regenerate() {
  if (!wasm) return;
  if (busy) { dirty = true; return; }
  busy = true; dirty = false;
  el.status.textContent = 'Generating…';
  setTimeout(() => {
    try {
      const p = params();
      const info = {}, bad = missingChars(bundled, p.text);
      const m = buildCap(wasm, bundled, { ...p, info });
      el.note.textContent = [
        bad.length ? `Not supported, so left out: ${bad.join(' ')}` : '',
        info.em > 0 && info.em < 3.2 ? `Letters are only about ${info.em.toFixed(1)} mm tall and may not print cleanly. Shorten the text for bigger letters.` : '',
      ].filter(Boolean).join(' ');
      const { pos, idx } = manifoldToArrays(m);
      current = { pos, idx, p };
      const g = new THREE.BufferGeometry();
      g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
      g.setIndex(new THREE.BufferAttribute(idx, 1));
      g.computeVertexNormals();
      if (mesh) { scene.remove(mesh); mesh.geometry.dispose(); }
      mesh = new THREE.Mesh(g, mat); scene.add(mesh);
      el.status.textContent = `Ready · ${(idx.length / 3).toLocaleString()} triangles · ${(({ square, width, height }) => `${square ? '' : 'Ø'}${width.toFixed(1)}${square ? ` × ${width.toFixed(1)}` : ''} × ${height.toFixed(1)} mm`)(capSize(p))}`;
      el.exportBtn.disabled = !el.cam.value;
      m.delete();
    } catch (e) {
      console.error(e);
      el.status.textContent = 'Something went wrong: ' + e.message;
    }
    busy = false;
    if (dirty) regenerate();
  }, 10);
}
const schedule = () => { clearTimeout(timer); timer = setTimeout(regenerate, 250); };

const count = () => { el.textCount.textContent = `${[...el.text.value].length} / ${el.text.maxLength}`; };
el.text.addEventListener('input', () => { count(); schedule(); });
count();
el.size.addEventListener('input', () => { el.sizeVal.textContent = el.size.value + '%'; schedule(); });
function fillGrips(square) {   // square caps only support the styles that work on a square outline
  const keep = el.grip.value;
  el.grip.length = 0;
  for (const [k, v] of Object.entries(GRIPS)) if (!square || SQUARE_GRIPS.includes(k)) el.grip.add(new Option(v, k));
  if ([...el.grip.options].some((o) => o.value === keep)) { el.grip.value = keep; return; }   // same style: keep the user's density
  el.grip.value = 'fluted'; el.count.value = DENSITY.fluted; el.countVal.textContent = el.count.value;
}
fillGrips(false);
el.grip.addEventListener('change', () => { el.count.value = DENSITY[el.grip.value]; el.countVal.textContent = el.count.value; schedule(); });
el.count.addEventListener('input', () => { el.countVal.textContent = el.count.value; schedule(); });
for (const c of CAMERAS) el.cam.add(new Option(c.name, c.id));
el.cam.addEventListener('change', () => { fillGrips(!!CAMERAS.find((c) => c.id === el.cam.value).shape); el.custom.value = CAMERAS.find((c) => c.id === el.cam.value).bore; el.exportBtn.disabled = !current; schedule(); });
el.fit.addEventListener('change', () => { el.customWrap.hidden = el.fit.value !== 'custom'; schedule(); });
el.custom.addEventListener('input', schedule);

el.exportBtn.addEventListener('click', () => {
  if (!current || !el.cam.value) return;
  const bytes = toBinarySTL(current.pos, current.idx);
  const slug = current.p.text.trim().toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-|-$/g, '').slice(0, 24) || (current.p.text.trim() ? 'text' : 'blank');
  const name = `${el.cam.value}-lens-cap_${slug}_${current.p.boreD.toFixed(1)}mm.stl`;
  const url = URL.createObjectURL(new Blob([bytes], { type: 'model/stl' }));
  const a = document.createElement('a'); a.href = url; a.download = name;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
  el.status.textContent = `Saved ${name}`;
});

// ---------- boot ----------
(async () => {
  try {
    el.status.textContent = 'Loading geometry engine…';
    bundled = fontBytes.map((b) => opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)));
    wasm = await Module({ wasmBinary: wasmBytes });
    wasm.setup();
    window.__capReady = true;
    regenerate();
  } catch (e) {
    console.error(e);
    el.status.textContent = 'Could not start: ' + e.message;
  }
})();
